//! Compiles the protos with protox (no protoc or buf needed), checks the
//! rules of spec/grpc.md §4, writes the operation table, and generates
//! messages, services and clients with connectrpc-build.

use prost_reflect::{DescriptorPool, DynamicMessage, Kind, MessageDescriptor, Value};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Read here only: its extensions describe the API, they aren't part of it.
const NOT_GENERATED: &[&str] = &["glidex/api/v1/options.proto"];

fn main() {
    let proto = PathBuf::from("proto");
    println!("cargo:rerun-if-changed=proto");

    let files = proto_files(&proto);
    let mut compiler = protox::Compiler::new([&proto]).unwrap_or_else(|e| fail(&e.to_string()));
    compiler.include_imports(true).include_source_info(true);
    compiler.open_files(&files).unwrap_or_else(|e| fail(&e.to_string()));
    let pool = compiler.descriptor_pool();

    let mut errors = Vec::new();
    check_json_names(&pool, &mut errors);
    let table = operations(&pool, &mut errors);
    check_secrets(&pool, &mut errors);
    if !errors.is_empty() {
        fail(&errors.join("\n"));
    }

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("operations.rs"), table).unwrap();
    let fds = out.join("glidex.fds");
    std::fs::write(&fds, compiler.encode_file_descriptor_set()).unwrap();

    let generate: Vec<&String> = files.iter().filter(|f| !NOT_GENERATED.contains(&f.as_str())).collect();
    connectrpc_build::Config::new()
        .descriptor_set(&fds)
        .files(&generate)
        .include_file("_connectrpc.rs")
        .emit_rerun_directives(false)
        .compile()
        .unwrap_or_else(|e| fail(&format!("{e:#}")));
}

fn fail(msg: &str) -> ! {
    eprintln!("glidex-api: {msg}");
    std::process::exit(1)
}

/// Every `.proto` under `dir`, as paths relative to it.
fn proto_files(dir: &Path) -> Vec<String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        let mut entries: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).collect();
        entries.sort();
        for p in entries {
            if p.is_dir() {
                walk(root, &p, out);
            } else if p.extension().is_some_and(|e| e == "proto") {
                out.push(p.strip_prefix(root).unwrap().to_string_lossy().replace('\\', "/"));
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, &mut out);
    out
}

fn ours(package: &str) -> bool {
    package == "glidex" || package.starts_with("glidex.")
}

/// G-D11: JSON names are the proto names, so REST stays snake_case.
fn check_json_names(pool: &DescriptorPool, errors: &mut Vec<String>) {
    for m in pool.all_messages().filter(|m| ours(m.package_name())) {
        for f in m.fields() {
            if f.json_name() != f.name() {
                errors.push(format!(
                    "{}.{}: JSON name is {:?}; declare [json_name = \"{}\"] (spec/grpc.md G-D11)",
                    m.full_name(),
                    f.name(),
                    f.json_name(),
                    f.name()
                ));
            }
        }
    }
}

/// The operation table (spec/grpc.md §5) as Rust source.
fn operations(pool: &DescriptorPool, errors: &mut Vec<String>) -> String {
    let Some(ext) = pool.get_extension_by_name("glidex.api.v1.op") else {
        errors.push("glidex.api.v1.op is not defined".into());
        return String::new();
    };
    let mut src = String::from("/// Every RPC of the API (generated by build.rs from the `glidex.api.v1.op` options).\npub static OPERATIONS: &[Operation] = &[\n");
    for s in pool.services().filter(|s| ours(s.package_name())) {
        for m in s.methods() {
            let name = format!("{}.{}", s.full_name(), m.name());
            let opts = m.options();
            if !opts.has_extension(&ext) {
                errors.push(format!("{name}: missing option (glidex.api.v1.op)"));
                continue;
            }
            let Value::Message(op) = opts.get_extension(&ext).into_owned() else { unreachable!() };
            let action = string(&op, "action");
            let rest = string(&op, "rest");
            let kind = match op.get_field_by_name("kind").map(|v| v.into_owned()) {
                Some(Value::EnumNumber(1)) => "Kind::Read",
                Some(Value::EnumNumber(2)) => "Kind::Write",
                _ => {
                    errors.push(format!("{name}: op.kind must be KIND_READ or KIND_WRITE"));
                    continue;
                }
            };
            if action.is_empty() {
                errors.push(format!("{name}: op.action is empty"));
            }
            let rest = match rest.split_once(' ') {
                None if rest.is_empty() => "None".to_string(),
                Some((method, path)) if ["GET", "POST", "PUT", "PATCH", "DELETE"].contains(&method) && path.starts_with('/') => {
                    format!("Some(({method:?}, {path:?}))")
                }
                _ => {
                    errors.push(format!("{name}: op.rest must be \"<METHOD> /path\", got {rest:?}"));
                    continue;
                }
            };
            let streaming = m.is_client_streaming() || m.is_server_streaming();
            writeln!(
                src,
                "    Operation {{ procedure: \"/{}/{}\", service: {:?}, method: {:?}, action: {:?}, kind: {kind}, rest: {rest}, streaming: {streaming} }},",
                s.full_name(),
                m.name(),
                s.full_name(),
                m.name(),
                action
            )
            .unwrap();
        }
    }
    src.push_str("];\n");
    src
}

fn string(m: &DynamicMessage, field: &str) -> String {
    match m.get_field_by_name(field).map(|v| v.into_owned()) {
        Some(Value::String(s)) => s,
        _ => String::new(),
    }
}

/// Secret fields are write-only: no RPC response may contain one, at
/// any depth (spec/grpc.md §4).
fn check_secrets(pool: &DescriptorPool, errors: &mut Vec<String>) {
    let Some(ext) = pool.get_extension_by_name("glidex.api.v1.secret") else {
        errors.push("glidex.api.v1.secret is not defined".into());
        return;
    };
    fn walk(m: &MessageDescriptor, ext: &prost_reflect::ExtensionDescriptor, seen: &mut BTreeSet<String>, path: &str, errors: &mut Vec<String>) {
        if !seen.insert(m.full_name().to_string()) {
            return;
        }
        for f in m.fields() {
            let here = format!("{path}.{}", f.name());
            let opts = f.options();
            if opts.has_extension(ext) && opts.get_extension(ext).as_bool() == Some(true) {
                errors.push(format!("{here}: a secret field is reachable from a response"));
            }
            if let Kind::Message(child) = f.kind() {
                walk(&child, ext, seen, &here, errors);
            }
        }
    }
    for s in pool.services().filter(|s| ours(s.package_name())) {
        for m in s.methods() {
            let out = m.output();
            walk(&out, &ext, &mut BTreeSet::new(), &format!("{}.{} → {}", s.name(), m.name(), out.name()), errors);
        }
    }
}
