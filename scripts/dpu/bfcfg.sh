#!/bin/bash
# Generates the bf.cfg that dpu-reinit.sh hands to bfb-install (spec/31-dpu.md §9.4.1).
# Sourced, not run. Reads: FW ATF TARGET OSUSER PUBLINE KEEP_PW CACERT AGENT.
# Writes the configuration to stdout. It contains public values only: no password,
# token or private key. Kept separate so test-hook.sh can exercise the hook offline.
#
# Design (spec §0 findings 23-26): the image's `ubuntu` account is left exactly as
# shipped. glidex gets its OWN account, created at first boot by a SHELL SCRIPT
# delivered as a second cloud-init seed file (vendor-data). A second `users:` list
# cannot be used: cloud-init strips `merge_how` when it saves vendor-data, so the
# shipped user-data's list silently replaces it (finding 26). The vendor script
# runs once per instance, as root, from cloud-init's scripts_vendor module. Nothing
# here creates, chowns or edits anything under any home directory at install time,
# and the shipped user-data is not modified.
gen_bf_cfg() {
(
  echo "# generated by dpu-reinit.sh; contains no password, token or private key"
  echo "UPDATE_DPU_OS=yes"
  echo "WITH_NIC_FW_UPDATE=$FW"
  echo "UPDATE_ATF_UEFI=$ATF"
  echo "device=$TARGET"
  echo
  echo "# public values the hook below uses"
  printf 'GLIDEX_USER=%s\n' "$OSUSER"
  printf "GLIDEX_KEY='%s'\n" "$PUBLINE"
  printf 'GLIDEX_KEEP_PW=%s\n' "$KEEP_PW"
  cat <<'HOOK_HEAD'

bfb_modify_os()
{
    # runs with the new root filesystem mounted at /mnt
    LOG=/mnt/var/log/glidex-bfcfg.log
    SEEDDIR=/mnt/var/lib/cloud/seed/nocloud-net
    KEYDIR=/mnt/etc/ssh/authorized_keys.d
    mkdir -p /mnt/var/log
    say() { echo "$*" >> $LOG; }
    say "bfb_modify_os start $(date -u +%FT%TZ)"
    for t in install chroot sed awk; do say "$t: $(command -v $t || echo MISSING)"; done
    say "account $GLIDEX_USER in the image passwd: $(grep -c "^$GLIDEX_USER:" /mnt/etc/passwd) (expected 0: cloud-init creates it at first boot)"
    say "shipped user-data present: $([ -f $SEEDDIR/user-data ] && echo yes || echo NO); vendor-data already present: $([ -f $SEEDDIR/vendor-data ] && echo YES || echo no)"

    # 1. The glidex account: a first-boot script as vendor-data (cloud-init saves it
    #    under scripts/vendor and runs it once per instance, as root). The values
    #    are substituted below; the script body is literal.
    if [ -d "$SEEDDIR" ] && [ ! -e "$SEEDDIR/vendor-data" ]; then
        cat > $SEEDDIR/vendor-data <<'GLIDEX_VD_EOF'
#!/bin/bash
# glidex bootstrap account: runs once, as root, at first boot (cloud-init scripts_vendor).
# GLIDEX_ROOT is empty on a DPU; the offline test points it at a scratch directory.
set -eu
U=@USER@
KEY='@KEY@'
R="${GLIDEX_ROOT:-}"
HOME_DIR="/var/lib/$U"
exec >> "$R/var/log/glidex-bootstrap.log" 2>&1
echo "glidex bootstrap start $(date -u +%FT%TZ)"
if ! id "$U" >/dev/null 2>&1; then
    useradd --system --create-home --home-dir "$HOME_DIR" --shell /bin/bash --comment "glidex service account" "$U"
fi
passwd -l "$U"
install -d -m 0700 -o "$U" -g "$U" "$R$HOME_DIR/.ssh"
printf '%s\n' "$KEY" > "$R$HOME_DIR/.ssh/authorized_keys"
chown "$U:$U" "$R$HOME_DIR/.ssh/authorized_keys"
chmod 0600 "$R$HOME_DIR/.ssh/authorized_keys"
printf '%s ALL=(ALL) NOPASSWD:ALL\n' "$U" > "$R/etc/sudoers.d/90-glidex"
chmod 0440 "$R/etc/sudoers.d/90-glidex"
visudo -cf "$R/etc/sudoers.d/90-glidex" || { rm -f "$R/etc/sudoers.d/90-glidex"; echo "sudoers entry rejected and removed"; exit 1; }
echo "glidex bootstrap done $(date -u +%FT%TZ)"
GLIDEX_VD_EOF
        sed -i -e "s|@USER@|$GLIDEX_USER|" -e "s|@KEY@|$GLIDEX_KEY|" $SEEDDIR/vendor-data
        chmod 0644 $SEEDDIR/vendor-data
        say "vendor-data (first-boot script) written for account $GLIDEX_USER"
    else
        say "vendor-data NOT written (seed dir missing, or a vendor-data already exists)"
    fi

    # 2. Fallback independent of cloud-init's user creation: the same key in a
    #    root-owned system path that sshd reads for that account. (A key file
    #    owned by root with mode 0600 is unreadable by the account and silently
    #    ignored, so this one is 0644.)
    install -d -m 0755 $KEYDIR
    printf '%s\n' "$GLIDEX_KEY" > $KEYDIR/$GLIDEX_USER
    chmod 0644 $KEYDIR/$GLIDEX_USER

    # 3. sshd policy as a drop-in (the shipped sshd_config includes the directory
    #    first, so a drop-in wins; the installer appends PasswordAuthentication yes
    #    at the end of sshd_config, which is why this must not live there).
    install -d -m 0755 /mnt/etc/ssh/sshd_config.d
    if [ "$GLIDEX_KEEP_PW" = 1 ]; then
        printf '%s\n' 'AuthorizedKeysFile .ssh/authorized_keys /etc/ssh/authorized_keys.d/%u' > /mnt/etc/ssh/sshd_config.d/10-glidex.conf
        say "sshd: password login left as the image ships it (--keep-password-login)"
    else
        printf '%s\n' 'AuthorizedKeysFile .ssh/authorized_keys /etc/ssh/authorized_keys.d/%u' 'PasswordAuthentication no' 'KbdInteractiveAuthentication no' > /mnt/etc/ssh/sshd_config.d/10-glidex.conf
    fi
HOOK_HEAD
  if [ -n "$CACERT" ]; then
    echo "    install -d -m 0755 /mnt/etc/glidex/ovn"
    echo "    cat > /mnt/etc/glidex/ovn/ca.pem <<'GLIDEX_CA_EOF'"
    cat "$CACERT"
    echo "GLIDEX_CA_EOF"
    echo "    chmod 644 /mnt/etc/glidex/ovn/ca.pem"
  fi
  if [ -n "$AGENT" ]; then
    echo "    install -d -m 0755 /mnt/opt/glidex"
    echo "    say 'agent package: copied by the operator after first boot (see runbook)'"
  fi
  cat <<'HOOK_TAIL'
    ls -ldn $KEYDIR $KEYDIR/$GLIDEX_USER $SEEDDIR/vendor-data /mnt/etc/ssh/sshd_config.d/10-glidex.conf >> $LOG 2>&1 || true
    say "--- sshd drop-in:"; cat /mnt/etc/ssh/sshd_config.d/10-glidex.conf >> $LOG 2>&1 || true
    say "--- vendor-data (key masked):"
    sed -E "s/^(KEY=').*'/\1<key>'/" $SEEDDIR/vendor-data >> $LOG 2>&1 || true
    say "bfb_modify_os done $(date -u +%FT%TZ)"
    # the host captures the installer console, not this file: show the log there too (it holds no secrets)
    for sink in /dev/console /dev/kmsg; do { echo '----- glidex bfb_modify_os log -----'; cat $LOG; echo '----- end glidex log -----'; } > $sink 2>/dev/null || true; done
    echo '----- glidex bfb_modify_os log -----'; cat $LOG; echo '----- end glidex log -----'
}
HOOK_TAIL
)
}
